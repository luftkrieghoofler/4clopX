import { readFileSync, writeFileSync } from 'node:fs';

const source = process.argv[2] || '../../gits/CLOP/clop/tables with data.sql';
const sql = readFileSync(source, 'utf8');

function tableRows(table) {
    const marker = `INSERT INTO \`${table}\``;
    let i = sql.indexOf(marker);
    if (i < 0) throw new Error(`No INSERT found for ${table}`);
    i = sql.indexOf('VALUES', i) + 6;
    const rows = [];

    const skipSpace = () => { while (/\s/.test(sql[i])) i += 1; };
    const value = () => {
        skipSpace();
        if (sql[i] !== "'") {
            const start = i;
            while (sql[i] !== ',' && sql[i] !== ')') i += 1;
            const raw = sql.slice(start, i).trim();
            if (/^null$/i.test(raw)) return null;
            return /^-?\d+(?:\.\d+)?$/.test(raw) ? Number(raw) : raw;
        }

        i += 1;
        let out = '';
        while (i < sql.length) {
            if (sql[i] === "'" && sql[i + 1] === "'") {
                out += "'";
                i += 2;
            } else if (sql[i] === "'") {
                i += 1;
                return out;
            } else if (sql[i] === '\\') {
                const escaped = { n: '\n', r: '\r', t: '\t', '0': '\0' }[sql[i + 1]];
                out += escaped === undefined ? sql[i + 1] : escaped;
                i += 2;
            } else {
                out += sql[i];
                i += 1;
            }
        }
        throw new Error(`Unterminated string in ${table}`);
    };

    while (i < sql.length) {
        skipSpace();
        if (sql[i] === ';') break;
        if (sql[i] === ',') { i += 1; continue; }
        if (sql[i] !== '(') throw new Error(`Expected a row in ${table} at ${i}`);
        i += 1;
        const row = [];
        while (true) {
            row.push(value());
            skipSpace();
            if (sql[i] === ')') { i += 1; break; }
            if (sql[i] !== ',') throw new Error(`Expected a comma in ${table} at ${i}`);
            i += 1;
        }
        rows.push(row);
    }
    return rows;
}

function visibleText(text) {
    const named = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };
    return String(text)
        .replace(/<br\s*\/?\s*>/gi, ' ')
        .replace(/<[^>]*>/g, '')
        .replace(/&(#x[\da-f]+|#\d+|amp|lt|gt|quot|apos|nbsp);/gi, (_, entity) => {
            if (entity[0] !== '#') return named[entity.toLowerCase()];
            const hex = entity[1].toLowerCase() === 'x';
            return String.fromCodePoint(parseInt(entity.slice(hex ? 2 : 1), hex ? 16 : 10));
        })
        .replace(/\s+/g, ' ')
        .trim();
}

const resources = new Map(tableRows('resourcedefs').map((row) => [row[0], {
    id: row[0], isBuilding: !!row[1], name: row[3],
}]));
const items = new Map();
for (const row of tableRows('recipeitems')) {
    const resource = resources.get(row[1]);
    if (!items.has(row[0])) items.set(row[0], []);
    items.get(row[0]).push({
        resourceId: row[1],
        name: resource.name,
        isBuilding: resource.isBuilding,
        consumed: !!row[2],
        amount: row[3],
    });
}

const actions = {};
for (const row of tableRows('recipes')) {
    const output = resources.get(row[4]);
    actions[row[0]] = {
        name: visibleText(row[2]),
        description: visibleText(row[3]),
        output: output ? {
            resourceId: output.id,
            name: output.name,
            isBuilding: output.isBuilding,
            amount: row[5],
        } : null,
        items: items.get(row[0]) || [],
    };
}

const upkeep = {};
for (const row of tableRows('resourcerequirements')) {
    const resource = resources.get(row[1]);
    if (!upkeep[row[0]]) upkeep[row[0]] = [];
    upkeep[row[0]].push({ resourceId: row[1], name: resource.name, amount: row[2] });
}

const output = 'src/data/actions.generated.js';
const overrideMarker = '// LIVE OVERRIDES (preserved by generator)';
let overrides = '';
try {
    const existing = readFileSync(output, 'utf8');
    const markerAt = existing.indexOf(overrideMarker);
    if (markerAt >= 0) overrides = `\n\n${existing.slice(markerAt).trim()}\n`;
} catch (error) {
    if (error.code !== 'ENOENT') throw error;
}

const generated = `// Generated by scripts/generate-action-data.mjs from the original CLOP SQL dump.\n` +
    `// Update the mechanics and normalized description together: the description is the\n` +
    `// runtime compatibility signature which prevents stale data from being used silently.\n\n` +
    `export const ACTION_CATALOG = ${JSON.stringify(actions, null, 4)};\n\n` +
    `export const BUILDING_UPKEEP = ${JSON.stringify(upkeep, null, 4)};\n` + overrides;

writeFileSync(output, generated);
console.log(`Generated ${Object.keys(actions).length} actions from ${source}`);
